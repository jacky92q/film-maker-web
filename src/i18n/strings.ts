// Parameterised helpers.
export const fmt = {
  daysAgo: (lang: Lang, n: number) => (lang === 'ko' ? `${n}일 전` : `${n} days ago`),
  slidesCount: (lang: Lang, n: number) => (lang === 'ko' ? `슬라이드 ${n}장` : n === 1 ? '1 slide' : `${n} slides`),
  photosAdded: (lang: Lang, n: number) => (lang === 'ko' ? `사진 ${n}장을 넣었어요` : `Added ${n} photos`),
  deleteFilmConfirm: (lang: Lang, title: string) =>
    lang === 'ko' ? `‘${title}’이(가) 영구적으로 삭제됩니다.` : `“${title}” will be permanently deleted.`,
  duration: (lang: Lang, seconds: number) => {
    const s = Math.round(seconds);
    if (s >= 60) {
      const m = Math.floor(s / 60);
      const r = s % 60;
      return lang === 'ko' ? (r ? `${m}분 ${r}초` : `${m}분`) : r ? `${m}m ${r}s` : `${m}m`;
    }
    return lang === 'ko' ? `${s}초` : `${s}s`;
  },
  loopCount: (lang: Lang, times: number) =>
    lang === 'ko' ? `약 ${times}번 반복` : `loops about ${times}×`,
};
